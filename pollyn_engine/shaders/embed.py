#!/usr/bin/env python3
"""Generate shim/shaders.h from .vert/.frag files in this directory."""

import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ENGINE_DIR = os.path.dirname(SCRIPT_DIR)
OUTPUT = os.path.join(ENGINE_DIR, "shim", "shaders.h")

# Shader groups in output order
SHADERS = [
    ("Flat Shader", [("flat.vert", "FLAT_VS"), ("flat.frag", "FLAT_FS")]),
    ("PBR Shader (Cook-Torrance BRDF + environment)", [("pbr.vert", "PBR_VS"), ("pbr.frag", "PBR_FS")]),
    ("Cell Shader (Trellis-style quantized lighting)", [("cell.vert", "CELL_VS"), ("cell.frag", "CELL_FS")]),
    ("Wire Shader (solid-color indexed edges)", [("wire.vert", "WIRE_VS"), ("wire.frag", "WIRE_FS")]),
    ("Line Shader (pass-through vertex color)", [("line.vert", "LINE_VS"), ("line.frag", "LINE_FS")]),
    ("Depth Shader (encode linear depth into RGBA8)", [("depth.vert", "DEPTH_VS"), ("depth.frag", "DEPTH_FS")]),
]

def glsl_to_c_string(text):
    """Convert raw GLSL to a C string literal (indented, one line per source line)."""
    lines = text.split("\n")
    # Remove trailing empty line if present (files end with \n)
    if lines and lines[-1] == "":
        lines = lines[:-1]
    parts = []
    for line in lines:
        escaped = line.replace("\\", "\\\\").replace('"', '\\"')
        parts.append('    "' + escaped + '\\n"')
    return "\n".join(parts)

def main():
    out = []
    out.append("/*")
    out.append(" * shaders.h -- AUTO-GENERATED by shaders/embed.py")
    out.append(" *")
    out.append(" * Do not edit by hand. Edit the .vert/.frag files in shaders/ instead.")
    out.append(" */")
    out.append("")
    out.append("#ifndef POLLYN_SHADERS_H")
    out.append("#define POLLYN_SHADERS_H")

    for section, files in SHADERS:
        out.append("")
        out.append("/* " + "=" * 64)
        out.append(" * " + section)
        out.append(" * " + "=" * 64 + " */")
        out.append("")
        for filename, varname in files:
            path = os.path.join(SCRIPT_DIR, filename)
            with open(path, "r") as f:
                src = f.read()
            out.append("static const char *" + varname + " =")
            out.append(glsl_to_c_string(src) + ";")
            out.append("")

    out.append("#endif /* POLLYN_SHADERS_H */")
    out.append("")

    content = "\n".join(out)
    with open(OUTPUT, "w") as f:
        f.write(content)
    print(f"Generated {OUTPUT}")

if __name__ == "__main__":
    main()
